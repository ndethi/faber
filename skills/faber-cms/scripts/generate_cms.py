def write_file(path: Path, content: str):
    """Write file, creating parent dirs."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    typer.secho("  ✓ " + str(path), fg=typer.colors.GREEN)


@app.command()
def generate(
    project_name: str = typer.Option("faber-cms", "--project-name", "-n"),
    output_dir: str = typer.Option("./faber-cms", "--output-dir", "-o"),
    content_types: str = typer.Option("[]", "--content-types", help="JSON array of content type definitions"),
    content_types_file: Optional[str] = typer.Option(None, "--content-types-file", help="Path to JSON file with content types"),
    production_domain: str = typer.Option("cms.example.com", "--production-domain"),
    staging_domain: str = typer.Option("dev-cms.example.com", "--staging-domain"),
    cf_access_emails: str = typer.Option("admin@example.com", "--cf-access-emails", help="Comma-separated emails for CF Access"),
    cf_access_groups: str = typer.Option("", "--cf-access-groups", help="Comma-separated groups for CF Access"),
):
    """Generate Faber CMS Worker project (Iteration A)."""
    out = Path(output_dir).resolve()
    out.mkdir(parents=True, exist_ok=True)

    # Parse content types
    if content_types_file:
        with open(content_types_file) as f:
            ct_data = json.load(f)
    else:
        ct_data = json.loads(content_types)

    if not isinstance(ct_data, list):
        ct_data = [ct_data]

    config = {
        "deploy_targets": {
            "production": {"domain": production_domain, "branch": "main"},
            "staging": {"domain": staging_domain, "branch": "dev"},
        },
        "cf_access_policy": {
            "emails": [e.strip() for e in cf_access_emails.split(",") if e.strip()],
            "groups": [g.strip() for g in cf_access_groups.split(",") if g.strip()],
        },
    }

    typer.secho(f"\nGenerating Faber CMS for '{project_name}'...", fg=typer.colors.BLUE, bold=True)
    typer.secho(f"Output: {out}", fg=typer.colors.CYAN)
    typer.secho(f"Content types: {[ct['name'] for ct in ct_data]}", fg=typer.colors.CYAN)
    typer.secho(f"Production: {production_domain}", fg=typer.colors.CYAN)
    typer.secho(f"Staging: {staging_domain}", fg=typer.colors.CYAN)

    # Generate files
    typer.secho("\n1. Generating D1 schema & migrations...", fg=typer.colors.YELLOW)
    write_file(out / "worker" / "src" / "db" / "schema.sql", generate_d1_schema(ct_data))
    write_file(out / "worker" / "src" / "db" / "migrations" / "0001_initial.sql", generate_migration_sql(ct_data))

    typer.secho("\n2. Generating Worker TypeScript...", fg=typer.colors.YELLOW)
    write_file(out / "worker" / "src" / "index.ts", generate_worker_index(ct_data))
    write_file(out / "worker" / "src" / "types.ts", generate_types_ts(ct_data))
    write_file(out / "worker" / "src" / "middleware" / "cf-access.ts", generate_cf_access_middleware())
