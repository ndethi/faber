def run_cmd(cmd: List[str], cwd: Optional[Path] = None, env: Optional[Dict] = None) -> subprocess.CompletedProcess:
    """Run command and return result."""
    merged_env = {**os.environ}
    if env:
        merged_env.update(env)
    return subprocess.run(cmd, capture_output=True, text=True, cwd=cwd, env=merged_env)


def generate_content_type_sql(content_type: Dict[str, Any]) -> str:
    """Generate SQL CREATE TABLE for a content type."""
    name = content_type["name"]
    fields = content_type.get("fields", [])

    columns = [
        "id INTEGER PRIMARY KEY AUTOINCREMENT",
        "collection_id INTEGER NOT NULL REFERENCES collections(id) ON DELETE CASCADE",
        "version INTEGER NOT NULL DEFAULT 1",
        "data JSON NOT NULL",
        "status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived'))",
        "created_at DATETIME DEFAULT CURRENT_TIMESTAMP",
        "updated_at DATETIME DEFAULT CURRENT_TIMESTAMP",
        "published_at DATETIME",
        "created_by TEXT",
        "updated_by TEXT",
    ]

    has_slug = any(f["name"] == "slug" for f in fields)
    if has_slug:
        columns.append("UNIQUE(collection_id, slug)")

    sql = "CREATE TABLE IF NOT EXISTS content_{name} (\n  ".format(name=name) + ",\n  ".join(columns) + "\n);"

    sql += "\nCREATE INDEX IF NOT EXISTS idx_content_{name}_collection ON content_{name}(collection_id);".format(name=name)
    sql += "\nCREATE INDEX IF NOT EXISTS idx_content_{name}_status ON content_{name}(status);".format(name=name)
    if has_slug:
        sql += "\nCREATE INDEX IF NOT EXISTS idx_content_{name}_slug ON content_{name}(slug);".format(name=name)
    sql += "\nCREATE INDEX IF NOT EXISTS idx_content_{name}_published_at ON content_{name}(published_at);".format(name=name)

    return sql


def generate_d1_schema(content_types: List[Dict[str, Any]]) -> str:
    """Generate complete D1 schema SQL."""
    lines = [
        "-- Faber CMS D1 Schema",
        "-- Generated by faber-cms skill",
        "",
        "-- Collections table (groups content types)",
        "CREATE TABLE IF NOT EXISTS collections (",
        "  id INTEGER PRIMARY KEY AUTOINCREMENT,",
        "  name TEXT NOT NULL UNIQUE,",
        "  display_name TEXT NOT NULL,",
        "  description TEXT,",
        "  content_type_name TEXT NOT NULL,",
        "  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,",
        "  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP",
        ");",
        "",
        "-- Content versions table (audit trail)",
        "CREATE TABLE IF NOT EXISTS content_versions (",
        "  id INTEGER PRIMARY KEY AUTOINCREMENT,",
        "  content_id INTEGER NOT NULL,",
        "  collection_id INTEGER NOT NULL,",
        "  version INTEGER NOT NULL,",
        "  data JSON NOT NULL,",
        "  status TEXT NOT NULL,",
        "  changed_by TEXT,",
        "  change_summary TEXT,",
        "  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,",
        "  FOREIGN KEY (content_id, collection_id) REFERENCES content_items(id, collection_id) ON DELETE CASCADE",
        ");",
        "",
        "CREATE INDEX IF NOT EXISTS idx_content_versions_content ON content_versions(content_id, collection_id);",
        "CREATE INDEX IF NOT EXISTS idx_content_versions_created ON content_versions(created_at);",
        "",
    ]

    for ct in content_types:
        lines.append("-- Content type: {0}".format(ct['name']))
        lines.append(generate_content_type_sql(ct))
        lines.append("")

    lines.append("-- Unified content view")
    lines.append("CREATE VIEW IF NOT EXISTS content_items AS")
    if content_types:
        union_parts = []
        for ct in content_types:
            union_parts.append("SELECT id, collection_id, version, data, status, created_at, updated_at, published_at, created_by, updated_by, 'content_{0}' as source_table FROM content_{0}".format(ct['name']))
        lines.append(" UNION ALL ".join(union_parts) + ";")
    else:
        lines.append("SELECT 0 as id, 0 as collection_id, 0 as version, '{}' as data, 'draft' as status, datetime('now') as created_at, datetime('now') as updated_at, null as published_at, null as created_by, null as updated_by, 'none' as source_table WHERE 0;")
    lines.append("")

    return "\n".join(lines)


def generate_migration_sql(content_types: List[Dict[str, Any]]) -> str:
    return """-- Migration: 0001_initial_schema
-- Generated by faber-cms skill

{0}
""".format(generate_d1_schema(content_types))


