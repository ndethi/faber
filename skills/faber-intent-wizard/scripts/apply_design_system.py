#!/usr/bin/env python3
"""
Faber Intent Wizard - Design System Applier

Invokes faber-design-system skill to get tokens and applies them to the generated project.
"""

import json
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Optional


def run_design_system(fixture: str, output_dir: Path, format: str = "all") -> Dict[str, Any]:
    """Run faber-design-system skill to generate tokens."""
    # Check if the skill exists first
    skill_path = Path(__file__).parent.parent.parent.parent / "skills" / "faber-design-system" / "scripts" / "design_system.py"
    if not skill_path.exists():
        print(f"  → Design system skill not found at {skill_path}, using fallback tokens")
        return {}

    cmd = [
        sys.executable,
        "-m", "skills.faber-design-system.scripts.design_system",
        "generate",
        "--fixture", fixture,
        "--output-dir", str(output_dir / "design-system-output"),
        "--format", format,
    ]

    try:
        result = subprocess.run(cmd, capture_output=True, text=True, cwd=Path(__file__).parent.parent.parent.parent, timeout=30)
    except subprocess.TimeoutExpired:
        print(f"Warning: faber-design-system timed out after 30s, using fallback tokens", file=sys.stderr)
        return {}

    if result.returncode != 0:
        print(f"Warning: faber-design-system failed: {result.stderr}", file=sys.stderr)
        return {}

    # Read generated tokens
    tokens_file = output_dir / "design-system-output" / "design-tokens.json"
    if tokens_file.exists():
        with open(tokens_file, "r") as f:
            return json.load(f)

    return {}


def apply_tokens_to_astro_config(tokens: Dict[str, Any], astro_config_path: Path) -> None:
    """Update astro.config.mjs to import design system tokens."""
    if not astro_config_path.exists():
        return

    content = astro_config_path.read_text()

    # Add design system import if not present
    if "design-tokens.css" not in content:
        # Find the imports section and add design tokens import
        lines = content.split("\n")
        new_lines = []
        imports_added = False

        for line in lines:
            new_lines.append(line)
            if line.strip().startswith("import") and not imports_added:
                # Add after last import
                pass

        # Simpler approach: add to the top of the file if it has a specific pattern
        if "export default defineConfig" in content:
            # Insert import before export
            import_line = 'import "./src/styles/design-tokens.css";\n'
            content = content.replace(
                "export default defineConfig",
                import_line + "export default defineConfig"
            )
            astro_config_path.write_text(content)


def apply_tokens_to_global_css(tokens: Dict[str, Any], global_css_path: Path) -> None:
    """Update global.css to use design tokens."""
    if not global_css_path.exists():
        return

    # The design system already generates design-tokens.css which should be imported
    # This function ensures the import exists
    content = global_css_path.read_text()

    if "@import" not in content and "design-tokens" not in content:
        # Add import at the top
        import_line = '@import "./design-tokens.css";\n\n'
        global_css_path.write_text(import_line + content)


