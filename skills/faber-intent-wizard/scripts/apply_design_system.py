def apply_design_system(config: Dict[str, Any], output_dir: Path) -> None:
    """Main function to apply design system to generated project."""
    fixture = config.get("fixture", "faber-brand")

    # Try to run faber-design-system skill
    tokens = run_design_system(fixture, output_dir)

    # If skill not available or failed, generate fallback tokens
    if not tokens:
        print("  → Using fallback design tokens (faber-design-system skill not available)")
        tokens = {"fallback": True}

    # Generate design-tokens.css in src/styles
    styles_dir = output_dir / "src" / "styles"
    styles_dir.mkdir(parents=True, exist_ok=True)
    generate_astro_design_tokens_css(tokens, styles_dir / "design-tokens.css")

    # Update astro.config.mjs
    astro_config = output_dir / "astro.config.mjs"
    apply_tokens_to_astro_config(tokens, astro_config)

    # Update global.css if exists
    global_css = output_dir / "src" / "styles" / "global.css"
    if global_css.exists():
        apply_tokens_to_global_css(tokens, global_css)

    print(f"  ✓ Design system ({fixture}) applied to {output_dir}")


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Apply design system to generated project")
    parser.add_argument("--fixture", default="faber-brand", help="Design system fixture")
